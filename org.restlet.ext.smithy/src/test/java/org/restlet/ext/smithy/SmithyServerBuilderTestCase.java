package org.restlet.ext.smithy;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.net.URI;
import java.time.Duration;
import java.util.HexFormat;
import java.util.List;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import org.restlet.Client;
import org.restlet.Context;
import org.restlet.Request;
import org.restlet.Response;
import org.restlet.data.MediaType;
import org.restlet.data.Method;
import org.restlet.data.Protocol;
import org.restlet.data.Reference;
import org.restlet.ext.smithy.generated.counter.client.CounterClient;
import org.restlet.ext.smithy.generated.counter.model.AddInput;
import org.restlet.ext.smithy.generated.counter.model.AddOutput;
import org.restlet.ext.smithy.generated.counter.model.Overflow;
import org.restlet.ext.smithy.generated.counter.service.AddOperation;
import org.restlet.ext.smithy.generated.counter.service.Counter;
import org.restlet.ext.smithy.internal.RestletServerProvider;
import org.restlet.ext.smithy.internal.RestletSmithyServer;
import org.restlet.representation.ByteArrayRepresentation;
import software.amazon.smithy.java.client.core.error.TransportException;
import software.amazon.smithy.java.core.error.CallException;
import software.amazon.smithy.java.server.Route;
import software.amazon.smithy.java.server.Server;

/**
 * An RPCv2 CBOR service generated by smithy-java, hosted by servers of {@link SmithyServerBuilder},
 * and called by the generated client over {@link SmithyClientAdapter}.
 */
class SmithyServerBuilderTestCase {
    private RestletSmithyServer server;
    private Client restlet;

    @AfterEach
    void stop() throws Exception {
        if (restlet != null) {
            restlet.stop();
        }
        if (server != null) {
            server.shutdown().get(10, TimeUnit.SECONDS);
        }
    }

    private static Counter counter() {
        return Counter.builder()
                .addAddOperation(
                        (AddOperation)
                                (input, context) -> {
                                    long total = input.getValue() + 1;
                                    if (total > 100) {
                                        throw Overflow.builder().total(total).build();
                                    }
                                    return AddOutput.builder()
                                            .total(total)
                                            .label(input.getLabel())
                                            .build();
                                })
                .build();
    }

    private void start(SmithyServerBuilder builder, boolean http2) throws Exception {
        server = (RestletSmithyServer) builder.endpoints(URI.create("http://localhost:0")).build();
        server.start();
        Context context = new Context();
        context.getParameters().set("followRedirects", "false");
        if (http2) {
            context.getParameters().set("httpClientTransportMode", "HTTP2");
        }
        restlet = new Client(context, Protocol.HTTP);
        restlet.start();
    }

    private String uri(String path) {
        return "http://localhost:" + server.getActualPorts().getFirst() + path;
    }

    private CounterClient client(String base) {
        return CounterClient.builder()
                .transport(new SmithyClientAdapter(restlet))
                .endpoint(uri(base))
                .build();
    }

    @ParameterizedTest
    @ValueSource(booleans = {false, true})
    void generatedClientCallsTheCborService(boolean http2) throws Exception {
        SmithyServerBuilder builder = new SmithyServerBuilder().addService(counter());
        if (http2) {
            Context context = new Context();
            context.getParameters().set("http.transport.protocol", "HTTP2");
            builder.context(context);
        }
        start(builder, http2);
        AddOutput output = client("").add(AddInput.builder().value(41L).label("ünï").build());
        assertEquals(42L, output.getTotal());
        assertEquals("ünï", output.getLabel());
    }

    /**
     * Pins a smithy-java 1.8.0 bug: its RPCv2 server serializes a modeled error without its {@code
     * __type}, so the client can't tell which error it is.
     */
    @Test
    void cborModeledErrorsLoseTheirTypeUpstream() throws Exception {
        start(new SmithyServerBuilder().addService(counter()), false);
        AddInput input = AddInput.builder().value(100L).label("x").build();
        CounterClient client = client("");
        CallException error = assertThrows(CallException.class, () -> client.add(input));
        assertFalse(error instanceof Overflow, error.toString());
    }

    /** The SDK validates the input: a raw CBOR call, which no client validated, gets a 400. */
    @Test
    void invalidInputIsRejected() throws Exception {
        start(new SmithyServerBuilder().addService(counter()), false);
        Request request = new Request(Method.POST, uri("/service/Counter/operation/Add"));
        // {"value": -1, "label": "x"}: the value is below its range.
        request.setEntity(
                new ByteArrayRepresentation(
                        HexFormat.of().parseHex("a26576616c756520656c6162656c6178"),
                        MediaType.valueOf("application/cbor")));
        request.getHeaders().add("smithy-protocol", "rpc-v2-cbor");
        Response response = restlet.handle(request);
        assertEquals(400, response.getStatus().getCode());
        assertEquals("rpc-v2-cbor", response.getHeaders().getFirstValue("smithy-protocol", true));
    }

    /** Services added under a path go to the route of that path prefix, as with the SDK. */
    @Test
    void callsGoToTheRouteOfTheirPathPrefix() throws Exception {
        start(new SmithyServerBuilder().addService("/service", counter()), false);
        assertEquals(
                2L, client("").add(AddInput.builder().value(1L).label("a").build()).getTotal());
        Response other = restlet.handle(new Request(Method.GET, uri("/other")));
        assertEquals(404, other.getStatus().getCode());
    }

    /** The longest matching prefix wins, whatever the order of the SDK's routes. */
    @Test
    void longestPathPrefixWins() throws Exception {
        Counter root =
                Counter.builder()
                        .addAddOperation(
                                (AddOperation)
                                        (input, context) -> AddOutput.builder().total(-1L).build())
                        .build();
        start(
                new SmithyServerBuilder()
                        .addService("/", root)
                        .addService("/serv", root)
                        .addService("/service", counter()),
                false);
        assertEquals(
                2L, client("").add(AddInput.builder().value(1L).label("a").build()).getTotal());
    }

    @Test
    void routesMatchTheirConnectorPortAndSchemeAndHostName() {
        Reference ref = new Reference("http://api.example.com:9000/service/Counter/operation/Add");
        assertTrue(matches(route().pathPrefix("/service"), ref));
        assertFalse(matches(route().pathPrefix("/other"), ref));
        assertTrue(matches(route().port(8080).protocol("http"), ref));
        // The port and scheme are the connector's, whatever the Host header says.
        assertFalse(matches(route().port(9000), ref));
        assertFalse(matches(route().protocol("https"), ref));
        assertTrue(matches(route().hostName("API.example.com"), ref));
        assertFalse(matches(route().hostName("other.com"), ref));
    }

    private static boolean matches(Route.Builder route, Reference ref) {
        return RestletSmithyServer.matches(route.build(), ref, "http", 8080);
    }

    /** A Host header naming another port doesn't reach the routes of that port. */
    @Test
    void hostHeaderPortsDontSelectRoutes() throws Exception {
        start(new SmithyServerBuilder().addService(counter()), false);
        int port = server.getActualPorts().getFirst();
        server.shutdown().get(10, TimeUnit.SECONDS);
        server =
                (RestletSmithyServer)
                        new SmithyServerBuilder()
                                .addService(route().port(port + 1).build())
                                .endpoints(URI.create("http://localhost:" + port))
                                .build();
        server.start();
        Request request = new Request(Method.POST, uri("/service/Counter/operation/Add"));
        request.setHostRef(new Reference("http://localhost:" + (port + 1)));
        assertEquals(404, restlet.handle(request).getStatus().getCode());
    }

    /** Routes matching hosts keep the order they were added in. */
    @Test
    void routesMatchingHostsKeepTheirOrder() throws Exception {
        Counter root =
                Counter.builder()
                        .addAddOperation(
                                (AddOperation)
                                        (input, context) -> AddOutput.builder().total(-1L).build())
                        .build();
        start(
                new SmithyServerBuilder()
                        .addService(
                                Route.builder()
                                        .hostName("localhost")
                                        .pathPrefix("/")
                                        .services(List.of(root))
                                        .build())
                        .addService(route().pathPrefix("/service").build()),
                false);
        assertEquals(
                -1L, client("").add(AddInput.builder().value(1L).label("a").build()).getTotal());
    }

    private static Route.Builder route() {
        return Route.builder().services(List.of(counter()));
    }

    @Test
    void limitsApplyToEachRoute() throws Exception {
        start(
                new SmithyServerBuilder()
                        .addService(counter())
                        .numberOfWorkers(1)
                        .maxRequestBytes(16)
                        .maxCallDuration(Duration.ofSeconds(5)),
                false);
        Request request = new Request(Method.POST, uri("/service/Counter/operation/Add"));
        request.setEntity(
                new ByteArrayRepresentation(new byte[64], MediaType.valueOf("application/cbor")));
        request.getHeaders().add("smithy-protocol", "rpc-v2-cbor");
        assertEquals(413, restlet.handle(request).getStatus().getCode());
    }

    @Test
    void invalidSettingsAreRejected() {
        var builder = new SmithyServerBuilder();
        assertThrows(IllegalArgumentException.class, () -> builder.numberOfWorkers(0));
        assertThrows(IllegalArgumentException.class, () -> builder.maxRequestBytes(0));
        assertThrows(IllegalArgumentException.class, () -> builder.maxCallDuration(Duration.ZERO));
        assertThrows(
                IllegalArgumentException.class, () -> builder.endpoints(URI.create("ftp://x:1")));
        assertThrows(IllegalArgumentException.class, () -> builder.endpoints(new URI[0]));
        for (String endpoint :
                List.of(
                        "http://localhost:1/api",
                        "http://localhost:1?q",
                        "http://localhost:1#f",
                        "http://u@localhost:1")) {
            assertThrows(
                    IllegalArgumentException.class,
                    () -> builder.endpoints(URI.create(endpoint)),
                    endpoint);
        }
        assertThrows(NullPointerException.class, () -> builder.maxCallDuration(null));
        assertThrows(
                IllegalArgumentException.class,
                () ->
                        new SmithyServerBuilder()
                                .addService(Route.builder().pathPrefix("/x").build())
                                .build());
        // No service.
        assertThrows(IllegalStateException.class, builder::build);
    }

    @Test
    void serverIsSingleUse() throws Exception {
        start(new SmithyServerBuilder().addService(counter()), false);
        assertThrows(IllegalStateException.class, server::start);
        CounterClient client = client("");
        server.shutdown().get(10, TimeUnit.SECONDS);
        // Shutting down again returns the same completed future.
        assertTrue(server.shutdown().isDone());
        AddInput input = AddInput.builder().value(1L).label("x").build();
        assertThrows(TransportException.class, () -> client.add(input));
    }

    @Test
    void startFailuresStopWhatStarted() throws Exception {
        start(new SmithyServerBuilder().addService(counter()), false);
        int taken = server.getActualPorts().getFirst();
        Server clash =
                new SmithyServerBuilder()
                        .addService(counter())
                        .endpoints(URI.create("http://localhost:" + taken))
                        .build();
        assertThrows(IllegalStateException.class, clash::start);
        clash.shutdown().get(10, TimeUnit.SECONDS);
    }

    @Test
    void providerIsNamedRestletAndYieldsToNetty() {
        var provider = new RestletServerProvider();
        assertEquals("restlet", provider.name());
        assertTrue(provider.priority() < 0, "After the SDK's Netty server");
        assertInstanceOf(SmithyServerBuilder.class, provider.serverBuilder());
    }
}
