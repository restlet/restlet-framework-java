package org.restlet.ext.smithy;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.sun.net.httpserver.HttpExchange;
import com.sun.net.httpserver.HttpServer;
import java.io.ByteArrayInputStream;
import java.io.IOException;
import java.net.InetSocketAddress;
import java.net.URLDecoder;
import java.nio.charset.StandardCharsets;
import java.util.Random;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.restlet.Client;
import org.restlet.Context;
import org.restlet.data.Protocol;
import org.restlet.ext.smithy.generated.client.GreeterClient;
import org.restlet.ext.smithy.generated.model.GreetInput;
import org.restlet.ext.smithy.generated.model.Refused;
import org.restlet.ext.smithy.generated.model.UploadInput;
import software.amazon.smithy.java.io.datastream.DataStream;

/**
 * A client generated by smithy-java from {@code src/test/smithy}, at build time, calls a service
 * through the transport, set explicitly or discovered.
 */
class GeneratedClientTestCase {
    private final AtomicReference<String> target = new AtomicReference<>();
    private HttpServer peer;
    private Client restlet;

    @BeforeEach
    void start() throws Exception {
        peer = HttpServer.create(new InetSocketAddress("localhost", 0), 0);
        peer.createContext("/", this::serve);
        peer.start();
        Context context = new Context();
        context.getParameters().set("followRedirects", "false");
        restlet = new Client(context, Protocol.HTTP);
        restlet.start();
    }

    @AfterEach
    void stop() throws Exception {
        peer.stop(0);
        restlet.stop();
    }

    /** Greets the name of the path, or refuses "nobody"; counts uploaded bytes. */
    private void serve(HttpExchange exchange) throws IOException {
        byte[] body = exchange.getRequestBody().readAllBytes();
        String path = exchange.getRequestURI().getRawPath();
        String query = exchange.getRequestURI().getRawQuery();
        target.set(path + (query == null ? "" : "?" + query));
        byte[] response;
        int status = 200;
        if (path.startsWith("/upload")) {
            exchange.getResponseHeaders().add("x-received", Integer.toString(body.length));
            exchange.sendResponseHeaders(200, -1);
            exchange.close();
            return;
        }
        String name = URLDecoder.decode(path.substring("/greet/".length()), StandardCharsets.UTF_8);
        if ("nobody".equals(name)) {
            status = 400;
            response =
                    "{\"__type\":\"restlet.test#Refused\",\"reason\":\"no one to greet\"}"
                            .getBytes(StandardCharsets.UTF_8);
        } else {
            String punctuation =
                    query == null
                            ? ""
                            : URLDecoder.decode(
                                    query.substring("punctuation=".length()),
                                    StandardCharsets.UTF_8);
            String message =
                    exchange.getRequestHeaders().getFirst("x-greeting") + ", " + name + punctuation;
            response = ("{\"message\":\"" + message + "\"}").getBytes(StandardCharsets.UTF_8);
        }
        exchange.getResponseHeaders().add("content-type", "application/json");
        exchange.sendResponseHeaders(status, response.length);
        exchange.getResponseBody().write(response);
        exchange.close();
    }

    private String endpoint() {
        return "http://localhost:" + peer.getAddress().getPort();
    }

    /** A generated client borrowing the Restlet client: nothing to close. */
    private GreeterClient client() {
        return GreeterClient.builder()
                .transport(new SmithyClientAdapter(restlet))
                .endpoint(endpoint())
                .build();
    }

    @Test
    void generatedClientCallsThroughTheTransport() {
        var output =
                client().greet(
                                GreetInput.builder()
                                        .name("Ann Lee/2")
                                        .punctuation("!?")
                                        .greeting("Héllo")
                                        .build());
        assertEquals("Héllo, Ann Lee/2!?", output.getMessage());
        assertEquals("/greet/Ann%20Lee%2F2?punctuation=%21%3F", target.get());
    }

    @Test
    void generatedClientGetsModeledErrors() {
        GreetInput input = GreetInput.builder().name("nobody").greeting("Hi").build();
        GreeterClient client = client();
        Refused refused = assertThrows(Refused.class, () -> client.greet(input));
        assertEquals("no one to greet", refused.getReason());
    }

    @Test
    void generatedClientStreamsAnUploadOfUnknownLength() {
        byte[] payload = new byte[2 * 1024 * 1024 + 1];
        new Random(4).nextBytes(payload);
        var output =
                client().upload(
                                UploadInput.builder()
                                        .body(
                                                DataStream.ofInputStream(
                                                        new ByteArrayInputStream(payload)))
                                        .build());
        assertEquals(Integer.toString(payload.length), output.getReceived());
    }

    /**
     * Built without a transport, the generated client discovers this one, which owns its client.
     */
    @Test
    void generatedClientDiscoversTheTransport() {
        GreeterClient client = GreeterClient.builder().endpoint(endpoint()).build();
        var transport = assertInstanceOf(SmithyClientAdapter.class, client.config().transport());
        try {
            assertTrue(transport.isClientOwned());
            assertEquals(
                    "Hi, Bo",
                    client.greet(GreetInput.builder().name("Bo").greeting("Hi").build())
                            .getMessage());
        } finally {
            // The generated client interface is not closeable: stop the owned client directly.
            transport.close();
        }
    }
}
