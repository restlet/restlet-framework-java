/**
 * A service generated by smithy-java from {@code src/test/smithy}, hosted by the adapter beside
 * another route, and called by the generated client over {@link SmithyClientAdapter}.
 */
class SmithyServerAdapterTestCase {
    private final Map<String, String> notes = new ConcurrentHashMap<>();
    private final CountDownLatch waitStarted = new CountDownLatch(1);
    private final CountDownLatch waitReleased = new CountDownLatch(1);
    private final CountDownLatch waitInterrupted = new CountDownLatch(1);
    private volatile boolean skipUploads;
    private volatile boolean waitAsync;
    private SmithyServerAdapter adapter;
    private Server server;
    private Client restlet;

    @AfterEach
    void stop() throws Exception {
        waitReleased.countDown();
        if (restlet != null) {
            restlet.stop();
        }
        if (server != null) {
            server.stop();
        }
        if (adapter != null) {
            adapter.stop();
        }
    }

    private Notes service() {
        Notes.WaitStage beforeWait =
                Notes.builder()
                        .addGetNoteOperation(
                                (GetNoteOperation)
                                        (input, context) -> {
                                            String text = notes.get(input.getId());
                                            if (text == null) {
                                                throw NoteNotFound.builder()
                                                        .id(input.getId())
                                                        .build();
                                            }
                                            return GetNoteOutput.builder().text(text).build();
                                        })
                        .addPutNoteOperation(
                                (PutNoteOperation)
                                        (input, context) -> {
                                            notes.put(input.getId(), input.getText());
                                            return PutNoteOutput.builder().build();
                                        })
                        .addRequiredUploadOperation(
                                (RequiredUploadOperation)
                                        (input, context) -> RequiredUploadOutput.builder().build())
                        .addUploadOperation(
                                (UploadOperation)
                                        (input, context) -> {
                                            try (InputStream body =
                                                    input.getBody().asInputStream()) {
                                                return UploadOutput.builder()
                                                        .received(
                                                                skipUploads
                                                                        ? skipAll(body)
                                                                        : body.transferTo(
                                                                                OutputStreams.NULL))
                                                        .build();
                                            } catch (IOException e) {
                                                throw new java.io.UncheckedIOException(e);
                                            }
                                        });
        if (waitAsync) {
            return beforeWait
                    .addWaitOperation(
                            (WaitOperationAsync)
                                    (input, context) -> {
                                        waitStarted.countDown();
                                        // Never completes.
                                        return new CompletableFuture<>();
                                    })
                    .build();
        }
        return beforeWait
                .addWaitOperation(
                        (WaitOperation)
                                (input, context) -> {
                                    waitStarted.countDown();
                                    try {
                                        waitReleased.await();
                                    } catch (InterruptedException e) {
                                        waitInterrupted.countDown();
                                        Thread.currentThread().interrupt();
                                        throw new IllegalStateException("interrupted", e);
                                    }
                                    return WaitOutput.builder().build();
                                })
                .build();
    }

    /** Starts the adapter, configured by the caller, beside an "/other" route. */
    private void start(boolean http2) throws Exception {
        if (adapter == null) {
            adapter = new SmithyServerAdapter();
        }
        adapter.getServices().add(service());
        adapter.start();
        Router router = new Router();
        router.attach(
                "/other",
                new Restlet() {
                    @Override
                    public void handle(Request request, Response response) {
                        response.setEntity("other", MediaType.TEXT_PLAIN);
                    }
                });
        adapter.attachTo(router);
        Context serverContext = new Context();
        if (http2) {
            serverContext.getParameters().set("http.transport.protocol", "HTTP2");
        }
        server = new Server(serverContext, Protocol.HTTP, 0, router);
        server.start();
        Context clientContext = new Context();
        clientContext.getParameters().set("followRedirects", "false");
        if (http2) {
            clientContext.getParameters().set("httpClientTransportMode", "HTTP2");
        }
        restlet = new Client(clientContext, Protocol.HTTP);
        restlet.start();
    }

    private String uri(String path) {
        return "http://localhost:" + server.getActualPort() + path;
    }

    private NotesClient client() {
        return NotesClient.builder()
                .transport(new SmithyClientAdapter(restlet))
                .endpoint(uri(""))
                .build();
    }

    private Response call(
            Method method, String path, org.restlet.representation.Representation body) {
        Request request = new Request(method, uri(path));
        request.setEntity(body);
        return restlet.handle(request);
    }

    @ParameterizedTest
    @ValueSource(booleans = {false, true})
    void generatedClientCallsTheGeneratedService(boolean http2) throws Exception {
        start(http2);
        NotesClient client = client();
        client.putNote(PutNoteInput.builder().id("a b").text("héllo").build());
        assertEquals("héllo", client.getNote(GetNoteInput.builder().id("a b").build()).getText());
        assertEquals("héllo", notes.get("a b"));
    }

    @Test
    void modeledErrorsReachTheClient() throws Exception {
        start(false);
        GetNoteInput input = GetNoteInput.builder().id("missing").build();
        NotesClient client = client();
        NoteNotFound error = assertThrows(NoteNotFound.class, () -> client.getNote(input));
        assertEquals("missing", error.getId());
    }

    /** The SDK validates the input: a raw call, which no client validated, gets a 400. */
    @Test
    void invalidInputIsRejected() throws Exception {
        start(false);
        Response tooLong =
                call(
                        Method.PUT,
                        "/notes/n1",
                        new StringRepresentation(
                                "{\"text\":\"" + "x".repeat(65) + "\"}",
                                MediaType.APPLICATION_JSON));
        assertEquals(400, tooLong.getStatus().getCode());
        assertTrue(
                tooLong.getHeaders()
                        .getFirstValue("x-amzn-errortype", true)
                        .equals("smithy.framework#ValidationException"),
                tooLong.getHeaders().toString());
        // Serialized once.
        assertEquals(1, tooLong.getHeaders().subList("x-amzn-errortype", true).size());
        assertTrue(tooLong.getEntityAsText().contains("text"));
        Response missing =
                call(
                        Method.PUT,
                        "/notes/n1",
                        new StringRepresentation("{}", MediaType.APPLICATION_JSON));
        assertEquals(400, missing.getStatus().getCode());
        assertTrue(notes.isEmpty());
    }

    /** The adapter's route only takes the calls of hosted operations. */
    @Test
    void otherRoutesKeepTheirCalls() throws Exception {
        start(false);
        Response other = call(Method.GET, "/other", null);
        assertEquals(200, other.getStatus().getCode());
        assertEquals("other", other.getEntityAsText());
        assertEquals(404, call(Method.GET, "/nothing/here", null).getStatus().getCode());
    }

    /**
     * Attached at two routing bases, the adapter resolves the operation below each: the parent's
     * best-match scoring of "/api/notes/a" misses, and doesn't hide "/notes/a" from the child.
     */
    @Test
    void operationsResolveBelowEachRoutingBase() throws Exception {
        adapter = new SmithyServerAdapter();
        adapter.getServices().add(service());
        adapter.start();
        Router child = new Router();
        adapter.attachTo(child);
        Router parent = new Router();
        parent.setDefaultMatchingMode(Router.MODE_BEST_MATCH);
        adapter.attachTo(parent);
        parent.attach("/api", child);
        server = new Server(Protocol.HTTP, 0, parent);
        server.start();
        restlet = new Client(Protocol.HTTP);
        restlet.start();
        Response response =
                call(
                        Method.PUT,
                        "/api/notes/a",
                        new StringRepresentation("{\"text\":\"t\"}", MediaType.APPLICATION_JSON));
        assertEquals(200, response.getStatus().getCode());
        assertEquals("t", notes.get("a"));
    }

    @ParameterizedTest
    @ValueSource(booleans = {false, true})
    void uploadOfUnknownLengthIsStreamedToTheOperation(boolean http2) throws Exception {
        start(http2);
        byte[] payload = new byte[3 * 1024 * 1024 + 5];
        new Random(5).nextBytes(payload);
        UploadOutput output =
                client().upload(
                                UploadInput.builder()
                                        .body(
                                                DataStream.ofInputStream(
                                                        new ByteArrayInputStream(payload)))
                                        .build());
        assertEquals(payload.length, output.getReceived());
    }

    /**
     * Request bodies are bounded, whether their size is announced or not. Over HTTP/2, the client
     * gets the early response while still sending the body.
     */
    @ParameterizedTest
    @ValueSource(booleans = {false, true})
    void largeRequestBodiesAreRejected(boolean announced) throws Exception {
        adapter = new SmithyServerAdapter();
        adapter.setMaxRequestBytes(1024 * 1024);
        start(true);
        byte[] payload = new byte[2 * 1024 * 1024];
        var body =
                new InputRepresentation(
                        new ByteArrayInputStream(payload), MediaType.APPLICATION_OCTET_STREAM);
        if (announced) {
            body.setSize(payload.length);
        }
        assertEquals(413, call(Method.POST, "/upload", body).getStatus().getCode());
    }

    /** Pins a smithy-java 1.8.0 bug: its server validation rejects a required streaming payload. */
    @Test
    void requiredStreamingPayloadsAreRejectedUpstream() throws Exception {
        start(false);
        Response response =
                call(
                        Method.POST,
                        "/required-upload",
                        new StringRepresentation("data", MediaType.APPLICATION_OCTET_STREAM));
        assertEquals(400, response.getStatus().getCode());
    }

    @Test
    void concurrentCallsAreBounded() throws Exception {
        adapter = new SmithyServerAdapter();
        adapter.setMaxConcurrentCalls(1);
        start(false);
        CompletableFuture<Response> first =
                CompletableFuture.supplyAsync(() -> call(Method.POST, "/wait", null));
        assertTrue(waitStarted.await(10, TimeUnit.SECONDS));
        assertEquals(503, call(Method.POST, "/wait", null).getStatus().getCode());
        waitReleased.countDown();
        assertEquals(200, first.get(10, TimeUnit.SECONDS).getStatus().getCode());
        // The slot is free again once the first response is sent.
        assertEquals(200, call(Method.POST, "/wait", null).getStatus().getCode());
    }

    /** Skipped bytes count toward the limit, too. */
    @Test
    void skippedRequestBytesAreBounded() throws Exception {
        adapter = new SmithyServerAdapter();
        adapter.setMaxRequestBytes(1024 * 1024);
        skipUploads = true;
        start(true);
        var body =
                new InputRepresentation(
                        new ByteArrayInputStream(new byte[2 * 1024 * 1024]),
                        MediaType.APPLICATION_OCTET_STREAM);
        assertEquals(413, call(Method.POST, "/upload", body).getStatus().getCode());
    }

    /** An asynchronous operation that never completes still ends at its deadline. */
    @Test
    void pendingAsyncOperationsEndAtTheirDeadline() throws Exception {
        adapter = new SmithyServerAdapter();
        adapter.setMaxCallDuration(Duration.ofMillis(300));
        adapter.setMaxConcurrentCalls(1);
        waitAsync = true;
        start(false);
        assertEquals(503, call(Method.POST, "/wait", null).getStatus().getCode());
        // Its slot is free again.
        assertEquals(503, call(Method.POST, "/wait", null).getStatus().getCode());
        assertEquals(200, call(Method.GET, "/other", null).getStatus().getCode());
    }

    @Test
    void operationsRunningTooLongAreInterrupted() throws Exception {
        adapter = new SmithyServerAdapter();
        adapter.setMaxCallDuration(Duration.ofMillis(300));
        start(false);
        assertEquals(503, call(Method.POST, "/wait", null).getStatus().getCode());
        assertTrue(waitInterrupted.await(5, TimeUnit.SECONDS));
    }

    @Test
    void clientDisconnectsInterruptTheOperation() throws Exception {
        start(false);
        Request request = new Request(Method.POST, uri("/wait"));
        CompletableFuture.runAsync(() -> restlet.handle(request));
        assertTrue(waitStarted.await(10, TimeUnit.SECONDS));
        request.abort();
        assertTrue(waitInterrupted.await(10, TimeUnit.SECONDS));
    }

    @Test
    void stoppingInterruptsRunningOperations() throws Exception {
        start(false);
        CompletableFuture.runAsync(() -> call(Method.POST, "/wait", null));
        assertTrue(waitStarted.await(10, TimeUnit.SECONDS));
        adapter.stop();
        assertTrue(waitInterrupted.await(5, TimeUnit.SECONDS));
        // Its route no longer takes any call.
        assertEquals(404, call(Method.POST, "/wait", null).getStatus().getCode());
    }

    @Test
    void configurationIsFixedOnceStarted() throws Exception {
        assertThrows(IllegalStateException.class, () -> new SmithyServerAdapter().start());
        start(false);
        assertThrows(IllegalStateException.class, () -> adapter.setMaxConcurrentCalls(2));
        assertThrows(
                IllegalArgumentException.class,
                () -> new SmithyServerAdapter().setMaxCallDuration(Duration.ZERO));
    }

    /** Skips a stream to its end, returning the bytes skipped. */
    private static long skipAll(InputStream in) throws IOException {
        long total = 0;
        while (true) {
            long skipped = in.skip(64 * 1024);
            if (skipped > 0) {
                total += skipped;
            } else if (in.read() < 0) {
                return total;
            } else {
                total++;
            }
        }
    }

    /** Output stream discarding its bytes. */
    private static final class OutputStreams {
        static final java.io.OutputStream NULL = java.io.OutputStream.nullOutputStream();
    }
}
